"""Generate the self-contained GitHub package and external helper component."""
from pathlib import Path
import shutil

root = Path(__file__).resolve().parents[1]
text = (root / 'esphome-smart-clock.yaml').read_text(encoding='utf-8')
text = text.replace('  build_path: C:/Users/nirbe/.esphome/build/${device_name}\n', '')
for key in ('api_encryption_key', 'wifi_ssid', 'wifi_password', 'fallback_ap_password'):
    text = text.replace('!secret ' + key, '${' + key + '}')
start = text.index('  includes:\n')
end = text.index('  on_boot:\n', start)
text = text[:start] + text[end:]
for name in ('timer-finished', 'volume-beep'):
    text = text.replace(f'file: media/{name}.wav',
        f'file: https://raw.githubusercontent.com/${{github_repo}}/v${{firmware_version}}/media/{name}.wav')
text += '''
external_components:
  - source:
      type: git
      url: https://github.com/${github_repo}.git
      ref: v${firmware_version}
    components: [smart_clock]
smart_clock:
'''
(root / 'packages').mkdir(exist_ok=True)
(root / 'packages/smart-clock.yaml').write_text('# Generated by tools/generate_remote_package.py; edit the root YAML.\n' + text, encoding='utf-8')
dest = root / 'components/smart_clock'
dest.mkdir(parents=True, exist_ok=True)
for name in ('audio_startup', 'system_health', 'clock_timer', 'alarm_schedule'):
    shutil.copyfile(root / f'src/{name}.h', dest / f'{name}.h')
